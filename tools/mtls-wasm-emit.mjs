#!/usr/bin/env node
/**
 * The social relay's TLS module, built from its Rust source rather than trusted as a binary.
 *
 * `apps/social-relay/src/mtls-wasm/` holds what the relay's BankID hop runs (docs/rfc/mtls-hop.md):
 * rustls compiled to WebAssembly, and the wasm-bindgen glue in front of it. A `.wasm` is the one
 * artifact in this repo a reviewer cannot read, so it is held to the three-marks rule in CLAUDE.md
 * the strict way: its source is `apps/social-relay/mtls-wasm/`, this is its producer, and
 * `--check` rebuilds it from that source and refuses the checked-in bytes if they differ by one.
 *
 * The build runs inside the image `apps/social-relay/mtls-wasm/Dockerfile` describes — a digest-
 * pinned Rust, Debian's clang, wasm-bindgen-cli at the version the crate pins — and always as
 * linux/amd64, so a laptop and a CI runner compile with the same toolchain on the same
 * architecture. The crate is copied to a fixed path and built `--locked` with the source and
 * registry paths remapped, so nothing host-specific lands in the module. Building it needs
 * Docker and nothing else; `pnpm build` does not run this, so a checkout without Docker still
 * builds — it uses the checked-in module, which is what this gate exists to vouch for.
 *
 *   node tools/mtls-wasm-emit.mjs           # (re)build into apps/social-relay/src/mtls-wasm/
 *   node tools/mtls-wasm-emit.mjs --check   # CI: fail if the checked-in files are not what this builds
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CRATE = 'apps/social-relay/mtls-wasm';
const OUT = 'apps/social-relay/src/mtls-wasm';
const CHECK = process.argv.includes('--check');
const PLATFORM = 'linux/amd64';

const HEADER = `GENERATED by tools/mtls-wasm-emit.mjs from ${CRATE}/ — do not edit by hand.`;

/**
 * The emitted files, keyed by what wasm-bindgen names them. The module itself carries no header.
 * The glue names its siblings by wasm-bindgen's names (its types, and the module its default
 * loader would fetch), so those are renamed with the files.
 */
const RENAMES = [
  ['mtls_wasm_bg.wasm', 'mtls-wasm.generated.wasm'],
  ['mtls_wasm.d.ts', 'mtls-wasm.generated.d.ts'],
];
const renamed = (s) => RENAMES.reduce((text, [from, to]) => text.replaceAll(from, to), s);
const FILES = [
  { from: 'mtls_wasm.js', to: 'mtls-wasm.generated.js', comment: (s) => `// ${HEADER}\n${renamed(s)}` },
  { from: 'mtls_wasm.d.ts', to: 'mtls-wasm.generated.d.ts', comment: (s) => `// ${HEADER}\n${renamed(s)}` },
  { from: 'mtls_wasm_bg.wasm', to: 'mtls-wasm.generated.wasm', comment: null },
];

function run(cmd, args, opts = {}) {
  return execFileSync(cmd, args, { stdio: ['ignore', 'inherit', 'inherit'], ...opts });
}

/** The image is named by its Dockerfile's hash, so a changed recipe is a new image, never a stale one. */
function image() {
  const dockerfile = fs.readFileSync(path.join(ROOT, CRATE, 'Dockerfile'));
  const tag = `substrat-mtls-wasm:${createHash('sha256').update(dockerfile).digest('hex').slice(0, 16)}`;
  try {
    execFileSync('docker', ['image', 'inspect', tag], { stdio: 'ignore' });
  } catch {
    run('docker', ['build', '--platform', PLATFORM, '-t', tag, '-f', path.join(ROOT, CRATE, 'Dockerfile'), path.join(ROOT, CRATE)]);
  }
  return tag;
}

/** Build into a fresh directory and return it. The crate is mounted read-only; `target/` never touches the checkout. */
function build() {
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'mtls-wasm-'));
  const script = [
    'set -eu',
    'cp -r /crate /build',
    'cd /build',
    // Paths a panic message or a debug section could carry, made the same on every host.
    'export RUSTFLAGS="--remap-path-prefix=/build=crate --remap-path-prefix=$CARGO_HOME=cargo"',
    'export CC_wasm32_unknown_unknown=clang AR_wasm32_unknown_unknown=llvm-ar',
    // The crate's own tests (`receive` against an in-memory server), natively, before the module is built.
    'cargo test --locked --quiet',
    'cargo build --locked --release --target wasm32-unknown-unknown',
    'wasm-bindgen --target web --out-dir /out target/wasm32-unknown-unknown/release/mtls_wasm.wasm',
  ].join('\n');
  run('docker', [
    'run', '--rm', '--platform', PLATFORM,
    '-v', `${path.join(ROOT, CRATE)}:/crate:ro`,
    '-v', `${out}:/out`,
    image(), 'sh', '-c', script,
  ]);
  return out;
}

/** What each emitted file should contain, from one build. */
function emitted(dir) {
  return FILES.map(({ from, to, comment }) => {
    const raw = fs.readFileSync(path.join(dir, from));
    return { to, bytes: comment ? Buffer.from(comment(raw.toString('utf8'))) : raw };
  });
}

const dir = build();
const files = emitted(dir);
fs.rmSync(dir, { recursive: true, force: true });

if (CHECK) {
  const stale = files.filter(({ to, bytes }) => {
    const target = path.join(ROOT, OUT, to);
    return !fs.existsSync(target) || !fs.readFileSync(target).equals(bytes);
  });
  if (stale.length) {
    for (const { to } of stale) console.error(`mtls-wasm: ${OUT}/${to} is not what ${CRATE}/ builds to`);
    console.error('Run `node tools/mtls-wasm-emit.mjs` (needs Docker) and commit the result.');
    process.exit(1);
  }
  console.log(`mtls-wasm: ${files.length} file(s) match a rebuild of ${CRATE}/`);
} else {
  fs.mkdirSync(path.join(ROOT, OUT), { recursive: true });
  for (const { to, bytes } of files) fs.writeFileSync(path.join(ROOT, OUT, to), bytes);
  console.log(`mtls-wasm: wrote ${files.map((f) => `${OUT}/${f.to}`).join(', ')}`);
}
