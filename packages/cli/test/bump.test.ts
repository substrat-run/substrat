const model = (mutate: (m: Json) => void): Classification => {
  const head = clone(MODEL);
  mutate(head);
  return classifyModel(JSON.stringify(MODEL), JSON.stringify(head));
};
const oas = (mutate: (d: Json) => void): Classification => {
  const head = clone(OAS);
  mutate(head);
  return classifyOpenApi(JSON.stringify(OAS), JSON.stringify(head));
};
/** The same mutation run backwards: the mutated document is the base, the fixture the head. */
const reverseOas = (mutate: (d: Json) => void): Classification => {
  const base = clone(OAS);
  mutate(base);
  return classifyOpenApi(JSON.stringify(base), JSON.stringify(OAS));
};
const perms = (edit: (t: string) => string): Classification => {
  const head = edit(PERMS);
  expect(head, 'the edit must change the fixture').not.toBe(PERMS);
  return classifyPermissions(PERMS, head);
};
