#!/usr/bin/env node
/**
 * Unit rate-card generator (#3321) — the models billed by something other than tokens.
 *
 * Regenerates `src/unit-rate-card.generated.ts` from LiteLLM's
 * model_prices_and_context_window.json. Separate from `update-rate-card.mjs` on purpose: that
 * script rewrites the whole token card from two live catalogs, so a unit-rate change made
 * through it would carry whatever the token catalogs moved that day into the same billing
 * diff. Each card is regenerated, and reviewed, on its own.
 *
 * Speech-to-text first. Workers AI bills it per minute of input audio, and not every model
 * reports the duration it billed (`@cf/openai/whisper` reports none), so the host counts the
 * one thing it knows exactly — the bytes of audio it sent — and the price is an ESTIMATE of the
 * duration from those bytes at `AUDIO_BYTES_PER_SECOND`. Owner decision, 2026-11-27: charge on
 * bytes and estimate, rather than leave the calls unpriced.
 *
 * The basis is 128 kb/s, a common bitrate for compressed speech (MP3, browser Opus/WebM at its
 * higher settings). Uncompressed 16 kHz 16-bit mono PCM is 32 000 B/s, so a WAV upload prices
 * at about twice its real duration, and a 32 kb/s Opus clip at about a quarter of it. Changing
 * the basis reprices every later line and nothing already recorded: it is part of the reviewed
 * diff, like a rate.
 *
 * Only LiteLLM carries these rates (models.dev lists no Workers AI speech model), so every row
 * is single-source and printed as such: verify against the provider's price page. Matched by
 * EXACT id, not prefix: `@cf/openai/whisper` is a prefix of `@cf/openai/whisper-tiny-en`, which
 * this card does not price.
 *
 * Run manually (`pnpm --filter @substrat-run/model-providers update-unit-rate-card`), never in
 * CI and never at runtime. Env override for an offline run: LITELLM_JSON = a file path.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const LITELLM_URL =
	'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json';

const AUDIO_BYTES_PER_SECOND = 16_000;

/** One row per model, by exact id; `per` is the LiteLLM field read. */
const SERVED_UNITS = [
	{ provider: 'cloudflare', id: '@cf/openai/whisper', label: 'Whisper', unit: 'audio-byte', litellm: 'cloudflare/@cf/openai/whisper', per: 'input_cost_per_second' },
	{ provider: 'cloudflare', id: '@cf/openai/whisper-large-v3-turbo', label: 'Whisper Large v3 Turbo', unit: 'audio-byte', litellm: 'cloudflare/@cf/openai/whisper-large-v3-turbo', per: 'input_cost_per_second' },
];

/** A per-second USD float as a per-1M-seconds decimal string; float noise washed out as the token card does. */
const per1M = (perSecond) => String(Number(Number(perSecond * 1e6).toPrecision(12)));

async function loadLiteLlm() {
	const local = process.env.LITELLM_JSON;
	if (local) return JSON.parse(await readFile(local, 'utf8'));
	const res = await fetch(LITELLM_URL);
	if (!res.ok) throw new Error(`${LITELLM_URL} → HTTP ${res.status}`);
	return res.json();
}

const liteLlm = await loadLiteLlm();
const rows = [];
const missing = [];
for (const u of SERVED_UNITS) {
	const name = `${u.provider}:${u.id}`;
	const raw = liteLlm[u.litellm];
	const perSecond = raw?.[u.per];
	if (typeof perSecond !== 'number' || !(perSecond >= 0)) {
		missing.push(`${name}: LiteLLM '${u.litellm}' has no ${u.per}`);
		continue;
	}
	console.warn(`note: ${name}: only in LiteLLM — single-source, verify against the provider price page`);
	rows.push({
		provider: u.provider,
		modelId: u.id,
		label: u.label,
		unit: u.unit,
		perMillionAudioSeconds: per1M(perSecond),
		bytesPerSecond: AUDIO_BYTES_PER_SECOND,
		sources: [`litellm:${u.litellm}`, raw.source ?? null].filter(Boolean),
	});
}
if (missing.length) {
	console.error('\nMISSING RATES — a served model would bill nothing:');
	for (const m of missing) console.error(`  ✗ ${m}`);
	process.exit(1);
}

const generatedAt = new Date().toISOString().slice(0, 10);
const srcDir = join(dirname(fileURLToPath(import.meta.url)), '..');
await writeFile(
	join(srcDir, 'src', 'unit-rate-card.generated.ts'),
	`/**
 * GENERATED by scripts/update-unit-rate-card.mjs from LiteLLM model_prices_and_context_window.json — DO NOT EDIT.
 *
 * Regenerate: pnpm --filter @substrat-run/model-providers update-unit-rate-card
 * (review the diff — like rate-card.generated.ts, this file is a billing checkpoint).
 *
 * The models billed by something other than tokens (#3321), by exact id. Speech-to-text:
 * USD list price per 1M seconds of audio (LiteLLM only — single-source), charged on the bytes
 * the host sent at \`bytesPerSecond\` — an ESTIMATE of the duration, stated beside the rate.
 */
import type { UnitRate } from './pricing.js';

export const UNIT_RATE_CARD_GENERATED_AT = '${generatedAt}';

export const UNIT_RATE_CARD: readonly UnitRate[] = ${JSON.stringify(rows, null, '\t')};
`,
);
console.log(`wrote unit rate card (${rows.length} models), generated ${generatedAt}`);
